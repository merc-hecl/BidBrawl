export function itemArtSource(item,catalog=[]){
  const id=item?.template_id||item?.id;
  if(!artworkIDs.has(id)||!item.name)return '';
  const template=catalog.find(entry=>entry.id===id);
  if(!template||template.name!==item.name)return '';
  return '/item-art/'+id+'.svg';
}

export function itemArtwork(item,catalog=[]){
  const src=itemArtSource(item,catalog);
  return src?`<img class="item-artwork" src="${esc(src)}" width="256" height="192" alt="" decoding="async">`:'';
}
